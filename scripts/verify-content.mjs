import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const source=readFileSync('src/data/content.ts','utf8');
const exports={};new Function('exports','require',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(exports,createRequire(import.meta.url));
assert.equal(exports.link(null),undefined);
assert.equal(exports.link('javascript:alert(1)'),undefined);
assert.equal(exports.link('not a url'),undefined);
assert.equal(exports.link('https://example.com'),'https://example.com');
assert.deepEqual(exports.list(null),[]);
assert.deepEqual(exports.list(['Python',null,'']),['Python']);
assert.deepEqual(exports.records([null,{},'bad']),[{}]);
assert.equal(exports.asset('certificates/missing.pdf','pdf'),undefined);
assert.equal(exports.asset('../package.json','pdf'),undefined);
assert.equal(exports.asset('portrait.jpg','image'),'portrait.jpg');
console.log('Optional fields, invalid links, missing assets, and path traversal verified.');
const load=(file,entries)=>{const result={};const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;new Function('exports','require',code)(result,name=>name==='./content'?exports:entries);return result;};
const minimalProjects=load('src/data/projects.ts',[{title:'Minimal',track:'science'},null,{title:'Bad track',track:'wrong'}]).projects;
assert.equal(minimalProjects.length,1);assert.deepEqual(minimalProjects[0].skills,[]);assert.equal(minimalProjects[0].live,undefined);
const minimalCerts=load('src/data/certificates.ts',[{title:'Standalone',track:'analytics'},{title:'Parent',track:'science',courses:[{title:'Course'},null]}]).certifications;
assert.deepEqual(minimalCerts[0].courses,[]);assert.equal(minimalCerts[1].courses.length,1);assert.equal(minimalCerts[1].courses[0].date,'');assert.equal(minimalCerts[1].courses[0].verify,undefined);
console.log('Minimal projects, standalone certifications, and courses with omitted fields verified.');
